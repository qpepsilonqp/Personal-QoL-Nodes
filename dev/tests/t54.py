import asyncio
from common import *
async def sel(pg, loc):
    return await loc.evaluate("i => [i.selectionStart, i.selectionEnd, i.value.length, document.activeElement === i]")
async def away(pg): await pg.mouse.move(1150, 650, steps=5); await pg.wait_for_timeout(600)
async def main():
    logs=[]
    async with async_playwright() as p:
        b, pg = await open_page(p, logs)
        await pg.evaluate(SETUP); await pg.wait_for_timeout(1500)
        await choose_root(pg); await pg.wait_for_timeout(1500)
        m = pg.locator("input.spll-search").first
        await m.click(); await pg.keyboard.type("anime"); await pg.wait_for_timeout(200)
        await away(pg)
        print("main: still has cursor after leaving:", (await sel(pg, m))[3], "| open:", await pg.evaluate("() => window._n.spll.mainOpen"))
        bx = await m.bounding_box()
        await pg.mouse.move(bx["x"]+20, bx["y"]+10, steps=4); await pg.wait_for_timeout(300)
        await pg.mouse.click(bx["x"]+20, bx["y"]+10); await pg.wait_for_timeout(100)
        print("  click on text after coming back:", await sel(pg, m))
        await pg.mouse.click(bx["x"]+24, bx["y"]+10); await pg.wait_for_timeout(100)
        print("  second click inside:", await sel(pg, m))
        await pg.keyboard.type("x"); await pg.wait_for_timeout(100)
        await pg.mouse.click(bx["x"]+20, bx["y"]+10); await pg.wait_for_timeout(100)
        print("  click while still typing:", await sel(pg, m))
        await away(pg)
        await pg.mouse.move(bx["x"]+bx["width"]-60, bx["y"]+10, steps=4); await pg.wait_for_timeout(300)
        await pg.mouse.click(bx["x"]+bx["width"]-60, bx["y"]+10); await pg.wait_for_timeout(100)
        print("  click far right after coming back (expect all selected):", await sel(pg, m))
        await pg.mouse.click(bx["x"]+bx["width"]-60, bx["y"]+10); await pg.wait_for_timeout(100)
        print("  second click far right (expect cursor at end):", await sel(pg, m))
        await pg.mouse.click(1180, 520); await pg.wait_for_timeout(200)
        await pg.mouse.click(bx["x"]+bx["width"]-80, bx["y"]+10); await pg.wait_for_timeout(150)
        print("  after clicking the canvas, click far right (expect all):", await sel(pg, m))
        await pg.click(".spll-strip .spll-gear"); await pg.wait_for_timeout(200)
        print("  build:", await pg.locator(".spll-build").inner_text())
        await pg.click(".spll-strip .spll-gear"); await pg.wait_for_timeout(200)
        await away(pg)
        # group search
        await pg.evaluate("() => { const c = window._n.spll; c.treeEl.scrollTop = 0; c.renderTreeWindow(); }")
        g = lambda: pg.locator(".spll-group:has(.spll-gname:text-is('styles')) .spll-gsearch")
        await pg.hover(".spll-group:has(.spll-gname:text-is('styles')) .spll-gsearch-icon"); await pg.wait_for_timeout(300)
        await g().click(); await pg.keyboard.type("soft"); await pg.wait_for_timeout(300)
        gb = await g().bounding_box()
        await pg.mouse.click(gb["x"]+14, gb["y"]+gb["height"]/2); await pg.wait_for_timeout(100)
        print("group: click inside while typing:", await sel(pg, g()))
        await away(pg)
        await pg.mouse.move(gb["x"]+14, gb["y"]+gb["height"]/2, steps=4); await pg.wait_for_timeout(300)
        await pg.mouse.click(gb["x"]+14, gb["y"]+gb["height"]/2); await pg.wait_for_timeout(100)
        print("  click after coming back:", await sel(pg, g()))
        await away(pg)
        # Search Files
        await pg.click(".spll-fs-btn"); await pg.wait_for_timeout(400); await pg.keyboard.type("cyber"); await pg.wait_for_timeout(300)
        f = pg.locator(".spll-fs-input")
        fb = await f.bounding_box()
        await pg.mouse.click(fb["x"]+12, fb["y"]+fb["height"]/2); await pg.wait_for_timeout(100)
        print("files: click inside while typing:", await sel(pg, f))
        await away(pg)
        await pg.click(".spll-fs-btn"); await pg.wait_for_timeout(400)
        print("  reopened:", await sel(pg, f))
        print("ERRORS", errs(logs)[:4])
        await b.close()
asyncio.run(main())
