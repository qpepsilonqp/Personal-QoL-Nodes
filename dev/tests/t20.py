async def tip(pg, sel):
    await pg.mouse.move(5,5); await pg.wait_for_timeout(100)
    await pg.hover(sel); await pg.wait_for_timeout(600)
    return (await pg.locator(".spll-tip").inner_text()).replace("\n"," | ")
